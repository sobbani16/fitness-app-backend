const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const request = require('supertest');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const url = new URL(process.env.DATABASE_URL || 'http://missing');
if (url.hostname !== '127.0.0.1' || !/^\/fitness_c09_[a-z0-9_]+$/.test(url.pathname)) throw new Error('Dedicated disposable localhost fitness_c09_* database required');
process.env.AUTH_TEST_BYPASS = 'false';
process.env.NODE_ENV = 'test';
process.env.AUTH_LINK_SECRET = 'ab'.repeat(32);
process.env.AUTH_PUBLIC_URL = 'http://localhost:4000';
process.env.AUTH_EMAIL_FROM = 'Fixture <accounts@example.test>';
process.env.RESEND_API_KEY = 'test-only-no-network';
const { getPrisma } = require('../src/lib/prisma');
const { hashPassword } = require('../src/services/authService');
const { provisionAdmin } = require('../src/services/adminProvisioning');
const db = getPrisma(), app = require('../src/app');
const ids = Array.from({ length: 4 }, () => randomUUID()), operator = `test-${randomUUID()}`;
const password = `Fixture-${randomUUID()}`;
const options = userId => ({ mode: 'bootstrap', userId, operator, reference: 'review-C09-fixture' });
const apply = (input, preview) => ({ ...input, apply: true, reviewed: true, expectedState: preview.expectedState });
const login = async userId => (await request(app).post('/auth/login').send({ email: `${userId}@example.test`, password }).expect(200)).body.token;
(async () => {
  // Never clean or modify somebody else's existing data, even in a test-prefixed database.
  assert.equal(await db.user.count(), 0, 'Use an empty dedicated test database');
  assert.equal(await db.userRole.count(), 0, 'Unexpected pre-existing grants');
  assert.equal(await db.auditLog.count(), 0, 'Unexpected pre-existing audits');
  try {
    const passwordHash = await hashPassword(password);
    await db.user.createMany({ data: ids.map((id, i) => ({ id, email: `${id}@example.test`, passwordHash: i === 3 ? null : passwordHash, emailVerifiedAt: i === 2 ? null : new Date() })) });
    const oldTokens = await Promise.all(ids.slice(0, 2).map(login));
    await request(app).get('/admin/users').set('Authorization', `Bearer ${oldTokens[0]}`).expect(403);
    const cli = spawnSync(process.execPath, [path.join(__dirname, 'provision-admin.js'), '--mode', 'bootstrap', '--user-id', ids[0], '--operator', operator, '--reference', 'review-C09-fixture'], { env: process.env, encoding: 'utf8' });
    assert.equal(cli.status, 0); assert.equal(JSON.parse(cli.stdout).applied, false); assert(!cli.stdout.includes(passwordHash));
    const refused = spawnSync(process.execPath, [path.join(__dirname, 'provision-admin.js'), '--mode', 'bootstrap', '--user-id', ids[0], '--operator', operator, '--reference', 'review-C09-fixture', '--apply'], { env: process.env, encoding: 'utf8' });
    assert.equal(refused.status, 1);
    const preview = await provisionAdmin(db, options(ids[0]));
    assert.equal(preview.applied, false); assert.equal(await db.userRole.count(), 0); assert.equal(await db.auditLog.count(), 0); assert.equal(await db.authSession.count(), 2);
    for (const userId of [ids[2], ids[3], randomUUID()]) await assert.rejects(provisionAdmin(db, options(userId)), /existing password-authenticated/);
    console.log('PASS: CLI preview is read-only and apply without confirmation fails; unverified, passwordless and missing targets rejected');
    const role = await db.role.findUnique({ where: { name: 'SUPER_ADMIN' } });
    const permission = await db.permission.findUnique({ where: { name: 'MANAGE_ROLES' } });
    await db.rolePermission.delete({ where: { roleId_permissionId: { roleId: role.id, permissionId: permission.id } } });
    await assert.rejects(provisionAdmin(db, options(ids[0])), /RBAC configuration/);
    await db.rolePermission.create({ data: { roleId: role.id, permissionId: permission.id } });
    await db.user.update({ where: { id: ids[0] }, data: { updatedAt: new Date(Date.now() + 1000) } });
    await assert.rejects(provisionAdmin(db, apply(options(ids[0]), preview)), /Preview is stale/);
    const fresh = await provisionAdmin(db, options(ids[0]));
    await assert.rejects(provisionAdmin(db, { ...apply(options(ids[0]), fresh), reference: 'different-review' }), /Preview is stale/);
    console.log('PASS: incomplete RBAC and changed target/review reject apply');
    const failingAudit = { $transaction: (fn, config) => db.$transaction(tx => fn({ ...tx, auditLog: { ...tx.auditLog, create: async () => { throw new Error('Injected audit failure'); } } }), config) };
    await assert.rejects(provisionAdmin(failingAudit, apply(options(ids[0]), fresh)), /Injected audit failure/);
    assert.equal(await db.userRole.count(), 0); assert.equal(await db.authSession.count(), 2); assert.equal(await db.auditLog.count(), 0);
    console.log('PASS: audit failure rolls back privilege grant and session revocation');
    const plans = await Promise.all(ids.slice(0, 2).map(id => provisionAdmin(db, options(id))));
    const concurrent = await Promise.allSettled(Array.from({ length: 8 }, (_, i) => provisionAdmin(db, apply(options(ids[i % 2]), plans[i % 2]))));
    assert.equal(concurrent.filter(r => r.status === 'fulfilled').length, 1);
    assert.equal(await db.userRole.count({ where: { roleId: role.id, active: true } }), 1);
    assert.equal(await db.auditLog.count({ where: { action: 'admin.bootstrap' } }), 1);
    const winner = concurrent.find(r => r.status === 'fulfilled').value.userId, loser = ids.slice(0, 2).find(id => id !== winner);
    const old = oldTokens[ids.indexOf(winner)];
    await request(app).get('/admin/users').set('Authorization', `Bearer ${old}`).expect(401);
    const freshToken = await login(winner);
    await request(app).get('/admin/users').set('Authorization', `Bearer ${freshToken}`).expect(200);
    await request(app).get('/admin/users').set('x-user-id', winner).expect(401);
    await assert.rejects(provisionAdmin(db, options(loser)), /Administrator history/);
    console.log('PASS: eight competing bootstraps create exactly one administrator; revoked token denied; fresh login gains RBAC; spoofed header denied');
    const recovery = { ...options(loser), mode: 'recover', reference: 'review-recovery-fixture' };
    const recoveryPreview = await provisionAdmin(db, recovery);
    await assert.rejects(provisionAdmin(db, { ...apply(recovery, recoveryPreview), reviewed: false }), /attestation/);
    await provisionAdmin(db, apply(recovery, recoveryPreview));
    assert.equal(await db.userRole.count({ where: { roleId: role.id, active: true } }), 2);
    await request(app).get('/admin/users').set('Authorization', `Bearer ${oldTokens[ids.indexOf(loser)]}`).expect(401);
    const audits = await db.auditLog.findMany({ where: { actorId: `operator:${operator}` } });
    assert.equal(audits.length, 2); assert(audits.every(a => a.afterData.reviewed && a.afterData.reference));
    assert(!JSON.stringify(audits).includes(password));
    await db.userRole.deleteMany({ where: { userId: { in: ids } } });
    await assert.rejects(provisionAdmin(db, options(winner)), /Administrator history/);
    console.log('PASS: reviewed recovery preserves other admins, revokes target sessions and audits; historical bootstrap blocks reuse even after grants removed');
  } finally {
    await db.authSession.deleteMany({ where: { userId: { in: ids } } });
    await db.userRole.deleteMany({ where: { userId: { in: ids } } });
    await db.auditLog.deleteMany({ where: { actorId: `operator:${operator}` } });
    await db.user.deleteMany({ where: { id: { in: ids } } });
  }
})().catch(() => { console.error('C09 integration failed. Inspect fixture assertions locally; no credentials printed.'); process.exitCode = 1; }).finally(() => db.$disconnect());
