#!/usr/bin/env node
// Reachability report — Phase 15 P1 deliverable.
//   node scripts/activity-safety-reachability-report.js
// Writes docs/clinical/activity-safety-reachability-report.md and prints a
// summary line. Classification is derived from the same engine the runtime
// uses — a rule is "reachable" only if a real input path can fire it.

const { RULES } = require('../src/services/activitySafety/rulesData');
const { ACTIVITIES } = require('../src/services/activitySafety/activityCatalog');
const { SYMPTOMS_URGENT, SYMPTOM_CODES, SYMPTOM_ALIASES, DERIVABLE_PROFILE_FLAGS } = require('../src/services/activitySafety/constants');
const { evaluateActivity } = require('../src/services/activitySafety/engine');
const fs = require('fs');
const path = require('path');

const MED_FLAG_CHANNEL = new Set(['heat_sensitivity', 'fluid_restriction', 'hypoglycemia_risk',
  'hyperglycemia_ketones', 'hypertension_uncontrolled', 'pregnancy_high_risk', 'high_fatigue', 'poor_sleep']);

const catToActivities = {};
for (const [id, a] of Object.entries(ACTIVITIES)) for (const c of a.demands.categories) (catToActivities[c] = catToActivities[c] || []).push(id);

function tokenReach(group, token) {
  if (['__any__', '__always__', '__match_activity__'].includes(token)) return 'reachable';
  if (token.includes('+')) return token.split('+').every(p => tokenReach(group, p) !== 'unreachable') ? 'reachable' : 'unreachable';
  switch (group) {
    case 'symptomCodes': return (SYMPTOM_CODES.has(token) || SYMPTOM_ALIASES[token]) ? 'reachable' : 'unreachable';
    case 'activityCategories': return catToActivities[token] ? 'reachable' : 'unreachable';
    case 'profileFlags':
      return DERIVABLE_PROFILE_FLAGS.has(token) ? 'reachable' : MED_FLAG_CHANNEL.has(token) ? 'med-flag-only' : 'unreachable';
    case 'envHazards': return ['smoke', 'aqi_very_unhealthy'].includes(token) ? 'unreachable' : 'reachable';
    default: return 'reachable';
  }
}

// A rule is executable iff at least one token in each specified group is
// producible (OR-within-group semantics). Structural mirrors are URGENT rules
// whose every symptomCodes token is urgent — the short-circuit precedes them.
function classify(rule) {
  const a = rule.appliesTo || {};
  const symptoms = a.symptomCodes || [];
  const urgentOnly = symptoms.length > 0
    && Object.entries(a).every(([g, v]) => !Array.isArray(v) || !v.length || g === 'symptomCodes')
    && symptoms.every(t => SYMPTOMS_URGENT.has(SYMPTOM_ALIASES[t] || t));
  if (urgentOnly && rule.effect === 'URGENT_ESCALATION') return { cls: 'mirror', dead: [] };

  const dead = [];
  for (const [g, tokens] of Object.entries(a)) {
    if (!Array.isArray(tokens) || !tokens.length) continue;
    if (tokens.every(t => tokenReach(g, t) === 'unreachable')) dead.push(g);
  }
  if (rule.inputStatus === 'unsupported_input') return { cls: 'unsupported', dead };
  if (dead.length) return { cls: 'inert', dead };
  return { cls: 'reachable', dead: [] };
}

const rows = RULES.map(r => ({ ...classify(r), r }));
const by = (c) => rows.filter(x => x.cls === c);
const total = RULES.length;
const reachable = by('reachable'), mirrors = by('mirror'), unsupported = by('unsupported'), inert = by('inert');

// Tested-case accounting: executable examples + dedicated reachability suite.
const TEST_FILE = path.join(__dirname, '../tests/activitySafety.reachability.test.js');
const reachabilityTestCount = fs.existsSync(TEST_FILE) ? (fs.readFileSync(TEST_FILE, 'utf8').match(/\btest\('/g) || []).length : 0;

const md = `# Activity Safety — Rule Reachability Report (auto-generated)

**Generated by** \`scripts/activity-safety-reachability-report.js\` — derived from engine matching semantics, not intent. Regenerate after any rule/engine change.

## Summary

| Metric | Count | Rules |
|---|---|---|
| **Total rules** | ${total} | — |
| **Reachable (real input path exists)** | ${reachable.length} | ${reachable.length <= 30 ? reachable.map(x => x.r.code).join(', ') : 'see review package'} |
| **Intentionally short-circuited (urgent mirrors)** | ${mirrors.length} | ${mirrors.map(x => x.r.code).join(', ')} |
| **Unsupported input (inactive by design)** | ${unsupported.length} | ${unsupported.map(x => x.r.code).join(', ')} |
| **Inert — unexplained dead trigger** | ${inert.length} | ${inert.map(x => x.r.code).join(', ') || 'none'} |
| **Clinical approval status** | ${total} DRAFT / 0 APPROVED | all rules pending qualified review |

## Accounting notes

- **Structural mirrors** (${mirrors.join(', ')}): \`evalMedical\` short-circuits to URGENT_ESCALATION on any active urgent symptom *before* rule iteration — urgent handling is always-on product safety and must not depend on rule review status. These rules document the urgent code list for review; they can never appear in \`ruleIds\`. Verified by executable example in the review package (structural path produces URGENT_ESCALATION; the mirror rule is absent from ruleIds).
- **Unsupported input** (${unsupported.join(', ')}): the product has no validated signal for the trigger tokens (\`distress_signals\`, \`compulsive_pattern_flags\`). The rules stay inactive via the \`inputStatus\` column rather than inferring signals from unvalidated proxies — a false positive here would misclassify a mental-health state.
- **Med-flag-only tokens**: some profileFlags (\`${[...MED_FLAG_CHANNEL].join(', ')}\`) are reachable only through the free-form \`medicationActivityFlags\` user-declaration channel. Rules using them fire only on explicit user entry — listed per-rule in the review package; the reviewer decides whether that channel is acceptable.
- **Tested cases**: ${total} generated executable examples (review package) + ${reachabilityTestCount} dedicated positive/negative/coexistence/missing-data reachability tests (\`tests/activitySafety.reachability.test.js\`).

## Per-rule classification

| Code | Name | Class | Dead groups (if any) |
|------|------|-------|----------------------|
${rows.map(x => `| ${x.r.code} | ${x.r.name} | ${x.cls} | ${x.dead.join(', ') || '—'} |`).join('\n')}

**Nothing here approves a rule.** All ${total} remain DRAFT until a qualified reviewer approves them with reviewer metadata; the DB CHECK constraint enforces it.
`;
fs.writeFileSync(path.join(__dirname, '../docs/clinical/activity-safety-reachability-report.md'), md);
console.log(`reachability: ${total} total · ${reachable.length} reachable · ${mirrors.length} mirrors · ${unsupported.length} unsupported · ${inert.length} inert (${inert.map(x => x.r.code).join(',') || 'none'})`);
